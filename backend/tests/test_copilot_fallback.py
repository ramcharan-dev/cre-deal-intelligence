"""Tests for multi-provider Copilot AI architecture with fallback.

Covers all 11 required scenarios:
1. Gemini key empty → Groq attempted.
2. Gemini unavailable (503) → Groq attempted.
3. Gemini succeeds → Groq not called.
4. Gemini fails (500) → Groq succeeds.
5. Gemini fails → Groq fails → deterministic fallback.
6. Both API keys empty → deterministic fallback (0 HTTP requests).
7. Invalid Gemini response → Groq fallback.
8. Gemini timeout → Groq fallback.
9. Groq timeout → deterministic fallback.
10. Source references remain intact.
11. Existing Copilot behavior still works without AI providers.
"""

import uuid
from datetime import UTC, datetime

import httpx
import pytest
from pydantic import SecretStr

from app.api.schemas import AnswerItem, CopilotAnswer, SourceRef
from app.core.config import Settings
from app.services.copilot_providers import (
    CopilotContext,
    create_copilot_router,
)


def make_dummy_context(
    question: str = "What is the fixed rate on Riverbend?",
    deal_name: str | None = "The Lofts at Riverbend",
    intent: str = "lowest_fixed_rate",
) -> CopilotContext:
    email_id = uuid.uuid4()
    ref = SourceRef(
        email_id=email_id,
        email_subject="Beacon term sheet",
        email_sender="jsmith@beaconagency.com",
        email_sent_at=datetime(2026, 10, 3, 12, 0, tzinfo=UTC),
        source_text="10-year fixed at 5.12%",
        label="Interest rate",
    )
    items = [
        AnswerItem(
            title="Beacon Agency Lending",
            text="5.12% fixed",
            deal_id=uuid.uuid4(),
            sources=[ref],
        )
    ]
    return CopilotContext(
        question=question,
        deal_id=uuid.uuid4(),
        deal_name=deal_name,
        intent=intent,
        items=items,
        context_text="[1] (FIELD) Interest rate: 5.12% — Beacon Agency Lending | Source: Beacon term sheet",
    )


async def dummy_fallback(context: CopilotContext) -> CopilotAnswer:
    return CopilotAnswer(
        question=context.question,
        intent=context.intent,
        mode="structured",
        deal_id=context.deal_id,
        deal_name=context.deal_name,
        answer="The lowest fixed rate on The Lofts at Riverbend is 5.12% from Beacon Agency Lending.",
        items=context.items,
    )


# ---------------------------------------------------------------- Test Scenarios


@pytest.mark.anyio
async def test_1_gemini_key_empty_groq_attempted(caplog) -> None:
    settings = Settings(
        gemini_api_key=None,
        groq_api_key=SecretStr("mock-groq-key"),
        copilot_provider_order="gemini,groq,deterministic",
    )

    gemini_called = False
    groq_called = False

    def transport_handler(request: httpx.Request) -> httpx.Response:
        nonlocal gemini_called, groq_called
        if "generativelanguage.googleapis.com" in str(request.url):
            gemini_called = True
            return httpx.Response(200, json={})
        if "api.groq.com" in str(request.url):
            groq_called = True
            return httpx.Response(
                200,
                json={"choices": [{"message": {"content": "Answer generated by Groq."}}]},
            )
        return httpx.Response(404)

    client = httpx.AsyncClient(transport=httpx.MockTransport(transport_handler))
    router = create_copilot_router(fallback_fn=dummy_fallback, settings=settings, http_client=client)

    with caplog.at_level("INFO"):
        answer = await router.answer(make_dummy_context())

    assert not gemini_called, "Gemini must not be called when API key is empty"
    assert groq_called, "Groq must be attempted when Gemini key is empty"
    assert answer.mode == "llm"
    assert answer.answer == "Answer generated by Groq."
    assert "Gemini unavailable → trying Groq" in caplog.text


