@pytest.mark.anyio
async def test_10_source_references_remain_intact() -> None:
    # Test that both LLM answers and deterministic answers preserve genuine SourceRef objects
    settings = Settings(
        gemini_api_key=SecretStr("mock-gemini-key"),
        groq_api_key=None,
    )

    def transport_handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(
            200,
            json={"candidates": [{"content": {"parts": [{"text": "Beacon offered 5.12% fixed."}]}}]},
        )

    client = httpx.AsyncClient(transport=httpx.MockTransport(transport_handler))
    router = create_copilot_router(fallback_fn=dummy_fallback, settings=settings, http_client=client)

    context = make_dummy_context()
    original_sources = context.items[0].sources

    answer = await router.answer(context)

    assert len(answer.items) == 1
    assert len(answer.items[0].sources) == 1
    src = answer.items[0].sources[0]
    assert src.email_subject == "Beacon term sheet"
    assert src.email_sender == "jsmith@beaconagency.com"
    assert src.source_text == "10-year fixed at 5.12%"
    assert src.label == "Interest rate"
    assert src.email_id == original_sources[0].email_id


@pytest.mark.anyio
async def test_11_existing_copilot_behavior_still_works_without_ai_providers() -> None:
    # When keys are empty, create_copilot_router routes directly to the fallback function
    settings = Settings(gemini_api_key=None, groq_api_key=None)

    called = False

    async def verify_fallback(ctx: CopilotContext) -> CopilotAnswer:
        nonlocal called
        called = True
        return CopilotAnswer(
            question=ctx.question,
            intent=ctx.intent,
            mode="structured",
            deal_id=ctx.deal_id,
            deal_name=ctx.deal_name,
            answer="Existing deterministic output",
            items=ctx.items,
        )

    router = create_copilot_router(fallback_fn=verify_fallback, settings=settings)
    answer = await router.answer(make_dummy_context())

    assert called is True
    assert answer.mode == "structured"
    assert answer.answer == "Existing deterministic output"
